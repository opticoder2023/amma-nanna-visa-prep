// Regenerates audio/index.js (which clips exist) and sw.js (offline cache list + version).
// Run after adding or changing content or audio:  node tools/build_site.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
import { existsSync } from "node:fs";
const ids = lang => !existsSync(join(root, "audio", lang)) ? [] : readdirSync(join(root, "audio", lang)).filter(f => f.endsWith(".mp3")).map(f => f.slice(0, -4)).sort();
const clips = { te: ids("te"), "te-m": ids("te-m"), en: ids("en") };
writeFileSync(join(root, "audio/index.js"),
  "// Generated by tools/build_site.mjs. Lists the pre-recorded clips shipped with the app.\n" +
  `export const PUBLIC_CLIPS = ${JSON.stringify(clips)};\n`);

const walk = dir => readdirSync(join(root, dir)).flatMap(f => statSync(join(root, dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]);
const SHELL = ["./", "index.html", "manifest.webmanifest", "icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png",
  ...walk("js"), "audio/index.js", ...walk("fonts").filter(f => f.endsWith(".woff2"))];
const AUDIO = Object.entries(clips).flatMap(([dir, list]) => list.map(i => `audio/${dir}/${i}.mp3`));
const h = createHash("sha256");
for (const f of [...SHELL.filter(f => f !== "./"), ...AUDIO]) h.update(f).update(readFileSync(join(root, f)));
const VERSION = h.digest("hex").slice(0, 10);

writeFileSync(join(root, "sw.js"), `/* Offline cache for the installed app. Generated by tools/build_site.mjs; version changes whenever any file changes. */
const VERSION = '${VERSION}';
const CACHE = 'visa-' + VERSION;
const SHELL = ${JSON.stringify(SHELL)};
const AUDIO = ${JSON.stringify(AUDIO)};

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await c.addAll(SHELL);
    // audio: cache in small batches in the background; a failed clip is fetched again when played
    for (let i = 0; i < AUDIO.length; i += 40) await Promise.all(AUDIO.slice(i, i + 40).map(u => c.add(u).catch(() => {})));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  // the page itself: network first so updates show up, cached copy when offline
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); return r; })
      .catch(() => caches.match('index.html')));
    return;
  }
  // app files and audio: cache first
  e.respondWith(caches.match(req, {ignoreSearch: true}).then(hit => hit || fetch(req).then(r => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return r;
  })));
});
`);
console.log(`audio: ${clips.te.length} te + ${clips["te-m"].length} te-m + ${clips.en.length} en; sw version ${VERSION}`);
